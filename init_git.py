import os
import subprocess
import sys

def run_git_command(args, cwd):
    """
    Executes a git command in a specific directory.
    Returns the stdout if successful, raises an exception otherwise.
    """
    try:
        # Use capture_output to keep the console clean and check=True to raise exceptions on non-zero exits
        result = subprocess.run(
            ["git"] + args,
            cwd=cwd,
            capture_output=True,
            text=True,
            check=True
        )
        return result.stdout.strip()
    except subprocess.CalledProcessError as e:
        # Re-raise with a more descriptive message including stderr
        raise RuntimeError(f"Git command failed: {' '.join(e.cmd)}\nError: {e.stderr.strip()}")
    except FileNotFoundError:
        raise RuntimeError("Git executable not found. Please ensure git is installed and in your PATH.")

def initialize_and_commit(repo_path, commit_message="Initial commit"):
    """
    Initializes a git repository at the given path and commits all current files.
    """
    # Convert to absolute path and ensure directory exists
    repo_path = os.path.abspath(repo_path)
    if not os.path.exists(repo_path):
        os.makedirs(repo_path)
        print(f"Created directory: {repo_path}")

    try:
        # 1. Initialize the repository if it doesn't already have a .git folder
        if not os.path.exists(os.path.join(repo_path, ".git")):
            run_git_command(["init"], repo_path)
            print("Initialized empty Git repository.")
        else:
            print("Git repository already initialized.")

        # 2. Stage all files in the directory
        # This handles the case where there might be no files yet
        run_git_command(["add", "."], repo_path)

        # 3. Check if there are changes to commit
        # 'git status --porcelain' is empty if there are no changes
        status = run_git_command(["status", "--porcelain"], repo_path)
        
        if not status:
            print("Nothing to commit (working tree clean).")
            return

        # 4. Perform the commit
        # Note: This requires git user.name and user.email to be configured globally
        # If they aren't, this command will fail.
        run_git_command(["commit", "-m", commit_message], repo_path)
        print(f"Successfully committed changes: '{commit_message}'")

    except RuntimeError as err:
        print(f"Error during git operation: {err}", file=sys.stderr)
        sys.exit(1)

