    # Example usage: Initialize the current directory
    target_directory = "."
    
    # Optional: Create a dummy file if the directory is empty for demonstration
    dummy_file = os.path.join(target_directory, "README.md")
    if not os.path.exists(dummy_file):
        with open(dummy_file, "w") as f:
            f.write("# My Repository\nGenerated by Python script.")

    initialize_and_commit(target_directory, "Initial commit from Python script")